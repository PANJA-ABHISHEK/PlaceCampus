/* ───────────── Overview ───────────── */

export function ScoreOverviewCard({
  analysis,
  previousScore,
  onReanalyze,
  reanalyzing,
  canReanalyze,
}: {
  analysis: ResumeAnalysis;
  previousScore: number | null;
  onReanalyze: () => void;
  reanalyzing: boolean;
  canReanalyze: boolean;
}) {
  const band = getScoreBand(analysis.overallScore);
  return (
    <section aria-labelledby="score-title" className={cn(cardClassName, "pc-enter")}>
      <div className="flex flex-col items-center gap-6 sm:flex-row sm:items-start">
        <AtsScoreRing score={analysis.overallScore} />
        <div className="min-w-0 flex-1 text-center sm:text-left">
          <div className="flex flex-wrap items-center justify-center gap-2 sm:justify-start">
            <h2 id="score-title" className="text-lg font-bold text-[hsl(var(--foreground))]">
              Estimated ATS compatibility
            </h2>
            <ScoreBandPill score={analysis.overallScore} />
          </div>
          <p className="mt-1 text-sm text-[hsl(var(--muted-foreground))]">{band.description}</p>
          {previousScore !== null && (
            <div className="mt-2">
              <ScoreDelta delta={analysis.overallScore - previousScore} />
            </div>
          )}
          <p className="mt-3 text-[15px] leading-relaxed text-[hsl(var(--foreground)/0.88)]">{analysis.summary}</p>
          <dl className="mt-4 flex flex-wrap justify-center gap-x-5 gap-y-1 text-xs text-[hsl(var(--muted-foreground))] sm:justify-start">
            <div>
              <dt className="inline">Assessed for: </dt>
              <dd className="inline font-semibold text-[hsl(var(--foreground))]">
                {analysis.targetRole}
                {analysis.targetRoleInferred && <span className="font-normal text-[hsl(var(--muted-foreground))]"> (inferred)</span>}
              </dd>
            </div>
            <div>
              <dt className="inline">File: </dt>
              <dd className="inline">{analysis.fileName}</dd>
            </div>
            <div>
              <dt className="inline">Analysed: </dt>
              <dd className="inline">{formatAnalysisDate(analysis.createdAt)}</dd>
            </div>
          </dl>
        </div>
      </div>
      <div className="mt-5 flex flex-col gap-3 border-t border-[hsl(var(--border))] pt-4 sm:flex-row sm:items-center sm:justify-between">
        <EstimateDisclaimer className="sm:max-w-[34rem]" />
        <button
          type="button"
          onClick={onReanalyze}
          disabled={!canReanalyze || reanalyzing}
          title={canReanalyze ? undefined : "Upload a resume to re-analyse"}
          className="inline-flex h-10 shrink-0 items-center justify-center gap-2 rounded-xl border border-[hsl(var(--border))] bg-white px-4 text-sm font-semibold text-[hsl(var(--foreground))] shadow-[var(--shadow-xs)] transition-colors hover:bg-[hsl(var(--muted))] disabled:cursor-not-allowed disabled:opacity-50"
        >
          {reanalyzing ? <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" /> : <RotateCcw className="h-4 w-4" aria-hidden="true" />}
          Re-analyse resume
        </button>
      </div>
    </section>
  );
}

function EssentialsChecklist({ signals }: { signals: ResumeSignals }) {
  const items: { label: string; ok: boolean }[] = [
    { label: "Email address", ok: signals.hasEmail },
    { label: "Phone number", ok: signals.hasPhone },
    { label: "LinkedIn profile", ok: signals.hasLinkedIn },
    { label: "GitHub or portfolio", ok: signals.hasGithubOrPortfolio },
    ...(["EDUCATION", "SKILLS", "PROJECTS", "EXPERIENCE"] as const).map((key) => ({
      label: `${SECTION_LABELS[key]} section`,
      ok: signals.sectionsFound.includes(key),
    })),
  ];
  return (
    <div>
      <h3 className="text-sm font-semibold text-[hsl(var(--foreground))]">Essentials we found</h3>
      <p className="mt-0.5 text-xs text-[hsl(var(--muted-foreground))]">Measured directly from your resume text.</p>
      <ul className="mt-3 grid grid-cols-[repeat(auto-fill,minmax(170px,1fr))] gap-2">
        {items.map((item) => (
          <li key={item.label} className="flex items-center gap-2 text-sm">
            {item.ok ? (
              <CircleCheck className="h-4 w-4 shrink-0 text-[hsl(var(--color-success))]" aria-hidden="true" />
            ) : (
              <CircleAlert className="h-4 w-4 shrink-0 text-[hsl(var(--color-warning))]" aria-hidden="true" />
            )}
            <span className={item.ok ? "text-[hsl(var(--foreground))]" : "text-[hsl(var(--foreground)/0.75)]"}>
              {item.label}
              <span className="sr-only">{item.ok ? ": found" : ": not found"}</span>
            </span>
          </li>
        ))}
      </ul>
      <dl className="mt-4 grid grid-cols-3 gap-2 text-center">
        {[
          { label: "Words", value: signals.wordCount },
          { label: "Bullets", value: signals.bulletCount },
          { label: "With metrics", value: signals.quantifiedBulletCount },
        ].map((stat) => (
          <div key={stat.label} className="rounded-xl bg-[hsl(var(--muted)/0.6)] px-2 py-2.5">
            <dt className="text-[11px] text-[hsl(var(--muted-foreground))]">{stat.label}</dt>
            <dd className="text-lg font-bold text-[hsl(var(--foreground))]">{stat.value}</dd>
          </div>
        ))}
      </dl>
    </div>
  );
}

/* ───────────── Tags, cards ───────────── */

export function KeywordTags({
  items,
  tone,
  empty,
}: {
  items: string[];
  tone: "missing" | "matching";
  empty: string;
}) {
  if (!items.length) return <p className="text-sm text-[hsl(var(--muted-foreground))]">{empty}</p>;
  return (
    <ul className="flex flex-wrap gap-2">
      {items.map((item) => (
        <li
          key={item}
          className={cn(
            "inline-flex items-center gap-1 rounded-full border px-3 py-1 text-[13px] font-medium",
            tone === "missing"
              ? "border-[hsl(var(--color-warning)/0.35)] bg-[hsl(var(--color-warning-light))] text-[hsl(32_90%_30%)]"
              : "border-[hsl(var(--color-success)/0.3)] bg-[hsl(var(--color-success-light))] text-[hsl(152_60%_26%)]",
          )}
        >
          {tone === "missing" ? <X className="h-3 w-3" aria-hidden="true" /> : <Check className="h-3 w-3" aria-hidden="true" />}
          {item}
        </li>
      ))}
    </ul>
  );
}

function InsightList({ title, items, tone }: { title: string; items: { title: string; detail: string }[]; tone: "strength" | "weakness" }) {
  const Icon = tone === "strength" ? ThumbsUp : ThumbsDown;
  return (
    <section className={cardClassName} aria-label={title}>
      <h3 className="flex items-center gap-2 text-base font-bold text-[hsl(var(--foreground))]">
        <span
          className={cn(
            "flex h-8 w-8 items-center justify-center rounded-lg",
            tone === "strength" ? "bg-[hsl(var(--color-success-light))] text-[hsl(var(--color-success))]" : "bg-[hsl(var(--color-warning-light))] text-[hsl(var(--color-warning))]",
          )}
        >
          <Icon className="h-4 w-4" aria-hidden="true" />
        </span>
        {title}
      </h3>
      {items.length ? (
        <ul className="mt-4 space-y-3">
          {items.map((item) => (
            <li key={item.title} className="rounded-xl bg-[hsl(var(--muted)/0.5)] px-4 py-3">
              <p className="text-sm font-semibold text-[hsl(var(--foreground))]">{item.title}</p>
              <p className="mt-1 text-[13px] leading-relaxed text-[hsl(var(--muted-foreground))]">{item.detail}</p>
            </li>
          ))}
        </ul>
      ) : (
        <p className="mt-3 text-sm text-[hsl(var(--muted-foreground))]">Nothing notable here.</p>
      )}
    </section>
  );
}

function TextIssueList({ items, kind }: { items: ResumeTextIssue[]; kind: "bullet" | "grammar" }) {
  if (!items.length) {
    return (
      <p className="text-sm text-[hsl(var(--muted-foreground))]">
        {kind === "bullet" ? "No weak bullet points found. Nice work." : "No grammar or spelling issues found."}
      </p>
    );
  }
  return (
    <ul className="space-y-3">
      {items.map((item) => (
        <li key={item.quote} className="rounded-xl border border-[hsl(var(--border))] p-4">
          <p className="text-[11px] font-semibold uppercase tracking-wide text-[hsl(var(--muted-foreground))]">In your resume</p>
          <blockquote className="mt-1 border-l-2 border-[hsl(var(--color-warning))] pl-3 text-sm text-[hsl(var(--foreground)/0.85)]">
            {item.quote}
          </blockquote>
          <p className="mt-2 text-[13px] text-[hsl(var(--muted-foreground))]">{item.issue}</p>
          <p className="mt-3 text-[11px] font-semibold uppercase tracking-wide text-[hsl(var(--color-success))]">
            {kind === "bullet" ? "Try instead" : "Correction"}
          </p>
          <p className="mt-1 flex items-start gap-2 rounded-lg bg-[hsl(var(--color-success-light))] px-3 py-2 text-sm text-[hsl(var(--foreground))]">
            <ArrowRight className="mt-0.5 h-4 w-4 shrink-0 text-[hsl(var(--color-success))]" aria-hidden="true" />
            {item.suggestion}
          </p>
        </li>
      ))}
    </ul>
  );
}

