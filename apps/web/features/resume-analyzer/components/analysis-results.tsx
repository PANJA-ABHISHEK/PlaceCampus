/* ───────────── Tabs ───────────── */

export function AnalysisDetails({ analysis }: { analysis: ResumeAnalysis }) {
  const [selectedTab, setTab] = React.useState("breakdown");
  const tab = selectedTab === "job" && !analysis.jobMatch ? "breakdown" : selectedTab;

  return (
    <Tabs value={tab} onValueChange={setTab} className="pc-enter">
      <TabsList className="flex h-auto w-full flex-wrap justify-start gap-1 rounded-2xl bg-[hsl(var(--muted)/0.7)] p-1">
        <TabsTrigger value="breakdown" className="gap-1.5 rounded-xl"><ListChecks className="h-4 w-4" aria-hidden="true" />Score breakdown</TabsTrigger>
        <TabsTrigger value="feedback" className="gap-1.5 rounded-xl"><ThumbsUp className="h-4 w-4" aria-hidden="true" />Strengths &amp; gaps</TabsTrigger>
        <TabsTrigger value="improve" className="gap-1.5 rounded-xl"><Lightbulb className="h-4 w-4" aria-hidden="true" />Improvements</TabsTrigger>
        {analysis.jobMatch && (
          <TabsTrigger value="job" className="gap-1.5 rounded-xl"><Briefcase className="h-4 w-4" aria-hidden="true" />Job match · {analysis.jobMatch.score}</TabsTrigger>
        )}
      </TabsList>

      <TabsContent value="breakdown" className="mt-5">
        <div className="grid grid-cols-1 gap-5 lg:grid-cols-[minmax(0,1.6fr)_minmax(0,1fr)]">
          <section className={cardClassName} aria-label="Category scores">
            <h3 className="text-base font-bold text-[hsl(var(--foreground))]">Category scores</h3>
            <p className="mb-5 mt-0.5 text-xs text-[hsl(var(--muted-foreground))]">
              Your overall score is the weighted average of these seven categories.
            </p>
            <CategoryBreakdown categories={analysis.categories} />
          </section>
          <section className={cardClassName} aria-label="Essentials">
            <EssentialsChecklist signals={analysis.signals} />
          </section>
        </div>
      </TabsContent>

      <TabsContent value="feedback" className="mt-5 space-y-5">
        <div className="grid grid-cols-1 gap-5 lg:grid-cols-2">
          <InsightList title="Strengths" items={analysis.strengths} tone="strength" />
          <InsightList title="Weaknesses" items={analysis.weaknesses} tone="weakness" />
        </div>
        <div className="grid grid-cols-1 gap-5 lg:grid-cols-2">
          <section className={cardClassName} aria-label="Missing skills">
            <h3 className="text-base font-bold text-[hsl(var(--foreground))]">Missing skills</h3>
            <p className="mb-3 mt-0.5 text-xs text-[hsl(var(--muted-foreground))]">
              Expected for a {analysis.targetRole} and not found anywhere in your resume. Add only those you genuinely have.
            </p>
            <KeywordTags items={analysis.missingSkills} tone="missing" empty="No obvious skill gaps for this role." />
          </section>
          <section className={cardClassName} aria-label="Missing keywords">
            <h3 className="text-base font-bold text-[hsl(var(--foreground))]">Missing keywords</h3>
            <p className="mb-3 mt-0.5 text-xs text-[hsl(var(--muted-foreground))]">Terms recruiters and ATS filters commonly search for.</p>
            <KeywordTags items={analysis.missingKeywords} tone="missing" empty="Your resume covers the common keywords for this role." />
          </section>
        </div>
      </TabsContent>

      <TabsContent value="improve" className="mt-5 space-y-5">
        <section className={cardClassName} aria-label="Recommendations">
          <h3 className="text-base font-bold text-[hsl(var(--foreground))]">Recommended next steps</h3>
          <ul className="mt-4 grid grid-cols-1 gap-3 md:grid-cols-2">
            {analysis.recommendations.map((item) => (
              <li key={item.title} className="rounded-xl border border-[hsl(var(--border))] p-4 transition-shadow hover:shadow-[var(--shadow-sm)]">
                <div className="flex flex-wrap items-center gap-2">
                  <span className={cn("rounded-full px-2 py-0.5 text-[11px] font-bold", PRIORITY_STYLES[item.priority])}>
                    {item.priority === "HIGH" ? "High priority" : item.priority === "MEDIUM" ? "Medium" : "Low"}
                  </span>
                  <span className="text-[11px] font-medium text-[hsl(var(--muted-foreground))]">{AREA_LABELS[item.area]}</span>
                </div>
                <p className="mt-2 text-sm font-semibold text-[hsl(var(--foreground))]">{item.title}</p>
                <p className="mt-1 text-[13px] leading-relaxed text-[hsl(var(--muted-foreground))]">{item.detail}</p>
              </li>
            ))}
          </ul>
        </section>

        <div className="grid grid-cols-1 gap-5 lg:grid-cols-2">
          <section className={cardClassName} aria-label="Weak bullet points">
            <h3 className="mb-4 flex items-center gap-2 text-base font-bold text-[hsl(var(--foreground))]">
              <PenLine className="h-4 w-4 text-[hsl(var(--primary))]" aria-hidden="true" />
              Bullet points to strengthen
            </h3>
            <TextIssueList items={analysis.weakBullets} kind="bullet" />
          </section>
          <div className="space-y-5">
            <section className={cardClassName} aria-label="Grammar and spelling">
              <h3 className="mb-4 flex items-center gap-2 text-base font-bold text-[hsl(var(--foreground))]">
                <SpellCheck className="h-4 w-4 text-[hsl(var(--primary))]" aria-hidden="true" />
                Grammar &amp; spelling
              </h3>
              <TextIssueList items={analysis.grammarIssues} kind="grammar" />
            </section>
            <section className={cardClassName} aria-label="Formatting issues">
              <h3 className="text-base font-bold text-[hsl(var(--foreground))]">Formatting</h3>
              {analysis.formattingIssues.length ? (
                <ul className="mt-3 space-y-2">
                  {analysis.formattingIssues.map((issue) => (
                    <li key={issue} className="flex items-start gap-2 text-sm text-[hsl(var(--foreground)/0.85)]">
                      <CircleAlert className="mt-0.5 h-4 w-4 shrink-0 text-[hsl(var(--color-warning))]" aria-hidden="true" />
                      {issue}
                    </li>
                  ))}
                </ul>
              ) : (
                <p className="mt-2 text-sm text-[hsl(var(--muted-foreground))]">No formatting problems found.</p>
              )}
            </section>
          </div>
        </div>

        {analysis.sectionFeedback.length > 0 && (
          <section className={cardClassName} aria-label="Section feedback">
            <h3 className="text-base font-bold text-[hsl(var(--foreground))]">Section-by-section feedback</h3>
            <div className="mt-4 grid grid-cols-1 gap-3 md:grid-cols-2">
              {analysis.sectionFeedback.map((entry) => (
                <div key={entry.area} className="rounded-xl bg-[hsl(var(--muted)/0.5)] p-4">
                  <p className="text-sm font-semibold text-[hsl(var(--foreground))]">{AREA_LABELS[entry.area]}</p>
                  <p className="mt-1 text-[13px] leading-relaxed text-[hsl(var(--muted-foreground))]">{entry.feedback}</p>
                  {entry.suggestions.length > 0 && (
                    <ul className="mt-2 space-y-1">
                      {entry.suggestions.map((s) => (
                        <li key={s} className="flex items-start gap-1.5 text-[13px] text-[hsl(var(--foreground)/0.85)]">
                          <ArrowRight className="mt-0.5 h-3.5 w-3.5 shrink-0 text-[hsl(var(--primary))]" aria-hidden="true" />
                          {s}
                        </li>
                      ))}
                    </ul>
                  )}
                </div>
              ))}
            </div>
          </section>
        )}
      </TabsContent>

      {analysis.jobMatch && (
        <TabsContent value="job" className="mt-5">
          <JobMatchPanel match={analysis.jobMatch} excerpt={analysis.jobDescriptionExcerpt} />
        </TabsContent>
      )}
    </Tabs>
  );
}

